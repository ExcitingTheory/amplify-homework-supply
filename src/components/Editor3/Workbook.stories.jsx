// Helper to generate mock embedding vectors for semantic search
// In production, these are generated by text-embedding-3-small (1536 dimensions)
// For mocking, we use a smaller vector with realistic-looking values
const generateMockEmbedding = (seed = 0) => {
  const dims = 128; // Reduced from 1536 for mock data
  const embedding = [];
  for (let i = 0; i < dims; i++) {
    // Generate pseudo-random values based on seed
    embedding.push(Math.sin(seed + i * 0.1) * 0.5);
  }
  return embedding;
};

